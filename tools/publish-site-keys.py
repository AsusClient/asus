#!/usr/bin/env python3
"""Publish key fingerprints for the website's download gate.

Reads the key store used by keysmith / site/server (keys.json) and writes
docs/assets/licenses.js containing only SHA-256 hashes, status and expiry.
Raw keys are never written and never leave this machine.

Run it after generating, revoking, expiring or deleting keys:

    python tools/publish-site-keys.py
    git add docs/assets/licenses.js && git commit -m "update site keys"
    git push

Defaults: site/server/keys.json -> docs/assets/licenses.js
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_STORE = ROOT / "site" / "server" / "keys.json"
DEFAULT_OUT = ROOT / "docs" / "assets" / "licenses.js"

KEY_RE = re.compile(r"^ASUS-[A-HJ-NP-Z2-9]{5}(-[A-HJ-NP-Z2-9]{5}){3}$")


def normalize(raw: str) -> str:
    """Same normalization as site/server/license.mjs."""
    cleaned = re.sub(r"[^A-Za-z0-9]", "", str(raw or "")).upper()
    if cleaned.startswith("ASUS"):
        cleaned = cleaned[4:]
    if len(cleaned) != 20:
        return ""
    key = "ASUS-" + "-".join(cleaned[i : i + 5] for i in range(0, 20, 5))
    return key if KEY_RE.match(key) else ""


def fingerprint(key: str) -> str:
    return hashlib.sha256(key.encode("utf-8")).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("store", nargs="?", default=str(DEFAULT_STORE))
    parser.add_argument("output", nargs="?", default=str(DEFAULT_OUT))
    args = parser.parse_args()

    store_path = Path(args.store)
    out_path = Path(args.output)

    try:
        store = json.loads(store_path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        print(f"no key store at {store_path}", file=sys.stderr)
        return 1
    except json.JSONDecodeError as error:
        print(f"invalid JSON in {store_path}: {error}", file=sys.stderr)
        return 1

    entries = store.get("keys", {}) if isinstance(store, dict) else {}
    if not isinstance(entries, dict):
        print("unexpected store format (expected {version, keys:{...}})", file=sys.stderr)
        return 1

    now_ms = datetime.now(tz=timezone.utc).timestamp() * 1000
    published: dict[str, dict] = {}
    skipped = 0

    for entry in entries.values():
        if not isinstance(entry, dict):
            skipped += 1
            continue
        key = normalize(entry.get("key", ""))
        if not key:
            skipped += 1
            continue

        revoked = bool(entry.get("revoked"))
        expires = entry.get("expiresAt")
        expired = isinstance(expires, (int, float)) and expires < now_ms
        status = "revoked" if revoked else ("expired" if expired else "active")

        published[fingerprint(key)] = {
            "status": status,
            "expiresAt": int(expires) if isinstance(expires, (int, float)) else None,
        }

    active = sum(1 for v in published.values() if v["status"] == "active")

    body = json.dumps(published, indent=2, sort_keys=True)
    stamp = datetime.now(tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    out_path.write_text(
        "/* =========================================================================\n"
        "   asus.wtf — key fingerprints for the download gate\n"
        "\n"
        "   Generated by tools/publish-site-keys.py from the local key store.\n"
        "   Contains SHA-256 hashes only: no raw keys, no notes, nothing reusable.\n"
        f"   Generated {stamp} · {active} active of {len(published)} published.\n"
        "   Re-run the tool and redeploy after generating or revoking keys.\n"
        "   ========================================================================= */\n\n"
        f"window.ASUS_SITE_LICENSES = {{\n"
        f'  generatedAt: "{stamp}",\n'
        f"  keys: {body},\n"
        "};\n",
        encoding="utf-8",
    )

    print(f"wrote {out_path.relative_to(ROOT)}")
    print(f"{len(published)} keys ({active} active), {skipped} skipped")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
